// BROWSER BACK / FORWARD
// ============================================================

window.addEventListener(
    "popstate",
    function (event) {

        const articleId =
            event.state &&
            event.state.articleId;


        if (articleId) {

            loadArticle(articleId);

        } else {

            const params =
                new URLSearchParams(
                    window.location.search
                );


            const id =
                parseInt(
                    params.get("id"),
                    10
                ) || 1;


            loadArticleWithoutURLChange(id);

        }

    }
);
